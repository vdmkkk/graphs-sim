def table(headers, rows, widths_cm, font_pt=10.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0]
    set_repeat_header(hdr)
    for i, htext in enumerate(headers):
        c = hdr.cells[i]
        set_cell_shading(c, "D9E2F3")
        c.paragraphs[0].text = ""
        run = c.paragraphs[0].add_run(htext)
        force_font(run); run.bold = True; run.font.size = Pt(font_pt)
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        c.paragraphs[0].paragraph_format.first_line_indent = Cm(0)
        c.paragraphs[0].paragraph_format.line_spacing = 1.0
        c.paragraphs[0].paragraph_format.space_after = Pt(0)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            c = cells[i]
            c.paragraphs[0].text = ""
            run = c.paragraphs[0].add_run(str(val))
            force_font(run); run.font.size = Pt(font_pt)
            c.paragraphs[0].alignment = (WD_ALIGN_PARAGRAPH.LEFT if i == 0
                                         else WD_ALIGN_PARAGRAPH.CENTER)
            c.paragraphs[0].paragraph_format.first_line_indent = Cm(0)
            c.paragraphs[0].paragraph_format.line_spacing = 1.0
            c.paragraphs[0].paragraph_format.space_after = Pt(0)
    for r in t.rows:
        for i, c in enumerate(r.cells):
            c.width = Cm(widths_cm[i])
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


