def p(content, align="both", indent=True, before=None, after=None, sz=None):
    para = doc.add_paragraph()
    if isinstance(content, str):
        content = [(content, {})]
    for text, o in content:
        r = para.add_run(text)
        force_font(r)
        if o.get("b"): r.bold = True
        if o.get("i"): r.italic = True
        if o.get("sz"): r.font.size = Pt(o["sz"])
        elif sz: r.font.size = Pt(sz)
    fmt = para.paragraph_format
    fmt.alignment = {"both": WD_ALIGN_PARAGRAPH.JUSTIFY,
                     "center": WD_ALIGN_PARAGRAPH.CENTER,
                     "left": WD_ALIGN_PARAGRAPH.LEFT,
                     "right": WD_ALIGN_PARAGRAPH.RIGHT}[align]
    if not indent:
        fmt.first_line_indent = Cm(0)
    if before is not None: fmt.space_before = Pt(before)
    if after is not None: fmt.space_after = Pt(after)
    return para


def h(text, level=1, number=None):
    label = f"{number} {text}" if number else text
    if level == 1:                       # названия глав — прописными буквами
        label = label.upper()
    para = doc.add_heading(label, level=level)
    for r in para.runs:
        force_font(r)
    return para


