def bullet(content):
    para = doc.add_paragraph()
    if isinstance(content, str):
        content = [(content, {})]
    pre = para.add_run("— "); force_font(pre)
    for text, o in content:
        r = para.add_run(text); force_font(r)
        if o.get("b"): r.bold = True
        if o.get("i"): r.italic = True
    fmt = para.paragraph_format
    fmt.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    fmt.left_indent = Cm(1.0)
    fmt.first_line_indent = Cm(-0.5)
    return para


